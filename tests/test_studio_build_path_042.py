"""0.1.47: a past checkout's Cargo output must not satisfy a new build."""
import importlib.util
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
STUDIO = ROOT / 'tools' / 'studio-desktop'
sys.path.insert(0, str(STUDIO))
import studio_binary


def load_builder():
    spec = importlib.util.spec_from_file_location('tavix_builder_042', STUDIO/'build_windows.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def fixture(root):
    (root/'src-tauri/icons').mkdir(parents=True)
    (root/'src-tauri/icons/icon.ico').write_bytes(b'R'*128)
    (root/'src-tauri/tauri.conf.json').write_text(json.dumps({
        'identifier': 'inc.thebigtree.tavix.studio', 'version': '0.1.60'}), encoding='utf-8')
    (root/'package.json').write_text(json.dumps({'version':'0.1.60'}), encoding='utf-8')
    return root/'src-tauri/target/studio-managed-build/release/tavix-studio.exe'


class NativeBuildPath042(unittest.TestCase):
    def test_stale_cached_binary_cannot_fake_successful_compiler_exit(self):
        builder = load_builder()
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)/'new-studio'
            expected=fixture(root)
            older=Path(d)/'old-studio'/'src-tauri/target/studio-managed-build/release/tavix-studio.exe'
            older.parent.mkdir(parents=True)
            older.write_bytes(b'MZ previous version: must not be staged')
            with mock.patch.object(builder, 'STUDIO', root), \
                 mock.patch.object(builder, 'ROOT', root.parent), \
                 mock.patch.object(builder, 'BIN', older), \
                 mock.patch.object(builder.sys, 'platform', 'win32'), \
                 mock.patch.object(builder, 'command_executable', return_value='npm.cmd'), \
                 mock.patch.object(builder, '_npm_install_healthy', return_value=True), \
                 mock.patch.object(builder.subprocess, 'run', return_value=mock.Mock(returncode=0)) as run:
                self.assertEqual(builder.build_native(), 1)
                self.assertEqual(run.call_count, 1)
                self.assertEqual(run.call_args.kwargs['env']['CARGO_TARGET_DIR'],
                                 str(expected.parents[1]))
                self.assertFalse(expected.exists())
                self.assertEqual(older.read_bytes(), b'MZ previous version: must not be staged')
                self.assertFalse((studio_binary.runtime_root(root)/'current.json').exists())

    def test_actual_active_root_output_is_staged_with_digest(self):
        builder = load_builder()
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)/'new-studio'
            expected=fixture(root)
            old=Path(d)/'previous.exe'
            old.write_bytes(b'MZ should not be read from old path')
            actual=b'MZ simulated Cargo output generated by this build'
            def mock_cargo(*args, **kwargs):
                expected.parent.mkdir(parents=True, exist_ok=True)
                expected.write_bytes(actual)
                return mock.Mock(returncode=0)
            with mock.patch.object(builder, 'STUDIO', root), \
                 mock.patch.object(builder, 'ROOT', root.parent), \
                 mock.patch.object(builder, 'BIN', old), \
                 mock.patch.object(builder.sys, 'platform', 'win32'), \
                 mock.patch.object(builder, 'command_executable', return_value='npm.cmd'), \
                 mock.patch.object(builder, '_npm_install_healthy', return_value=True), \
                 mock.patch.object(builder.subprocess, 'run', side_effect=mock_cargo):
                self.assertEqual(builder.build_native(), 0)
            receipt = json.loads((studio_binary.runtime_root(root)/'current.json').read_text(encoding='utf-8'))
            self.assertEqual(receipt['version'], '0.1.60')
            self.assertEqual(receipt['sha256'], studio_binary._hash(expected))
            staged = studio_binary.runtime_root(root)/'0.1.60'/receipt['sha256'][:16]/'tavix-studio.exe'
            self.assertEqual(staged.read_bytes(), actual)
            self.assertEqual(old.read_bytes(), b'MZ should not be read from old path')

if __name__ == '__main__':
    unittest.main()
